# Golf ball on a tee, the menu cursor. Colours: . clear, w white, l light
# grey, d dark grey, t tee, s tee shadow. 7 x 10, drawn at 2x on 320 screens.
BALL = [
    '..www..',
    '.wwwwl.',
    'wwwwwll',
    'wwlwwll',
    'wwwwlld',
    '.wllld.',
    '..ddd..',
    '.ttttt.',
    '...t...',
    '...s...',
]
BALL_COLOURS = {'.': 0, 'w': 1, 'l': 2, 'd': 3, 't': 4, 's': 5}


def bits(rows):
    return [[1 if c == '#' else 0 for c in r] + [0] for r in rows]


def scale2x(g):
    """scale2x on a 0/1 grid."""
    h, w = len(g), len(g[0])
    o = [[0] * (2 * w) for _ in range(2 * h)]
    def at(x, y):
        return g[min(h - 1, max(0, y))][min(w - 1, max(0, x))]
    for y in range(h):
        for x in range(w):
            p = g[y][x]
            a, b, c, d = at(x, y - 1), at(x + 1, y), at(x - 1, y), at(x, y + 1)
            o[2 * y][2 * x] = a if (c == a and c != d and a != b) else p
            o[2 * y][2 * x + 1] = b if (a == b and a != c and b != d) else p
            o[2 * y + 1][2 * x] = c if (d == c and d != b and c != a) else p
            o[2 * y + 1][2 * x + 1] = d if (b == d and b != a and d != c) else p
    return o


def tall(g):
    """8x16 from 8x8: scale2x, then back to 8 columns. A column keeps its
    pixel unless both halves changed, so only full rounding steps show."""
    s = scale2x(g)
    out = []
    for y in range(16):
        row = []
        for x in range(8):
            p = g[y // 2][x]
            l, r = s[y][2 * x], s[y][2 * x + 1]
            row.append(l if l == r else p)
        out.append(row)
    return out


def rowbyte(row):
    v = 0
    for i, b in enumerate(row):
        if b:
            v |= 0x80 >> i
    return v


def main():
    chars = [chr(c) for c in range(32, 127)]
    missing = [c for c in chars if c not in G]
    assert not missing, missing
    small = [bits(G[c]) for c in chars]
    big = [tall(g) for g in small]
    L = ['/* Made by tools/mkfont.py, don\'t edit. Only font.c includes it. */',
         '#define FONT_FIRST 32', '#define FONT_COUNT 95', '',
         '/* 8x8, one byte a row, bit 7 the left column. */',
         'static const uint8_t font8[95 * 8] = {']
    for c, g in zip(chars, small):
        L.append('\t' + ', '.join('0x%02X' % rowbyte(r) for r in g) + ',   /* %s */' % ('space' if c == ' ' else c.replace('\\', 'backslash').replace('*', 'star').replace('/', 'slash')))
    L += ['};', '', '/* 8x16, the same layout. */', 'static const uint8_t font16[95 * 16] = {']
    for c, g in zip(chars, big):
        L.append('\t' + ', '.join('0x%02X' % rowbyte(r) for r in g) + ',')
    L += ['};', '', '/* Golf ball cursor, %d x %d, one UI colour slot a pixel (0 = clear). */' % (len(BALL[0]), len(BALL)),
          '#define BALL_W %d' % len(BALL[0]), '#define BALL_H %d' % len(BALL),
          'static const uint8_t ball_spr[%d] = {' % (len(BALL) * len(BALL[0]))]
    for r in BALL:
        L.append('\t' + ', '.join(str(BALL_COLOURS[c]) for c in r) + ',')
    L += ['};', '']
    OUT.write_text('\n'.join(L))
    if len(sys.argv) > 1:
        preview(chars, small, big, sys.argv[1])


def preview(chars, small, big, path):
    from PIL import Image
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    img = Image.new('RGB', (cols * 10 * 3 + cols * 18 * 2, rows * 18 * 2), (20, 60, 30))
    px = img.load()
    for i, (s, b) in enumerate(zip(small, big)):
        cx, cy = (i % cols) * 10 * 3, (i // cols) * 18 * 2
        for y in range(8):
            for x in range(8):
                if s[y][x]:
                    for dy in range(3):
                        for dx in range(3):
                            px[cx + x * 3 + dx, cy + y * 3 + dy] = (240, 230, 200)
        bx = cols * 30 + (i % cols) * 18 * 2
        for y in range(16):
            for x in range(8):
                if b[y][x]:
                    for dy in range(2):
                        for dx in range(4):
                            px[bx + x * 4 + dx, cy + y * 2 + dy] = (240, 230, 200)
    img.save(path)


if __name__ == '__main__':
    main()
