/* Sony CLIE Jog Dial key characters. Values are from Sony's published CLIE SDK API (SonyChars.h).
 * They come in keyDown events with commandKeyMask set. */
#ifndef SONYKEYS_H
#define SONYKEYS_H
#define vchrJogUp    0x1700     /* turned up */
#define vchrJogDown  0x1701     /* turned down */
#define vchrJogPush  0x1705     /* pressed in */
#define vchrJogBack  0x1707     /* the Back button */
#endif
